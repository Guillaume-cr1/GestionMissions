        private void chargerAgents() {
        try {
            AgentDAO dao = new AgentDAO();
            lesAgents = dao.listerAgents();

            jComboBoxAgent.removeAllItems();

            for (Agent agent : lesAgents) {
                jComboBoxAgent.addItem(
                    agent.getIdAgent() + " - "
                    + agent.getPseudo() + " "
                    + agent.getNom()
                );
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "Erreur lors du chargement des agents : "
                    + ex.getMessage());
            }
        }
        
            private void chargerMissions() {
            try {
                MissionDAO dao = new MissionDAO();
                lesMissions = dao.lister2();

                jComboBoxMission.removeAllItems();

                for (Mission mission : lesMissions) {
                    jComboBoxMission.addItem(mission.getTitre());
                }

            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this,
                        "Erreur lors du chargement des missions : "
                        + ex.getMessage());
            }
        }
