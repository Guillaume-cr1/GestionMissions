    private void btnAjouterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAjouterActionPerformed
      int indexAgent = jComboBoxAgent.getSelectedIndex();
    int indexMission = jComboBoxMission.getSelectedIndex();

    String role = txtRole.getText().trim();
    String dateTexte = txtDate.getText().trim();

    if (indexAgent < 0 || indexMission < 0
            || role.isEmpty() || dateTexte.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Veuillez remplir tous les champs.");
        return;
    }

    try {
        Agent agent = lesAgents.get(indexAgent);
        Mission mission = lesMissions.get(indexMission);

        LocalDate date = LocalDate.parse(dateTexte);

        Participation participation = new Participation(
                agent.getIdAgent(),
                mission.getId(),
                role,
                date
        );

        ParticipationDAO dao = new ParticipationDAO();
        dao.ajouter(participation);

        JOptionPane.showMessageDialog(this,
                "Affectation ajoutée avec succès !");

        txtRole.setText("");
        txtDate.setText("");

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this,
                    "La date doit être au format AAAA-MM-JJ (exemple : 2026-11-21).");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erreur lors de l'ajout : " + e.getMessage());
        }
    }//GEN-LAST:event_btnAjouterActionPerformed

