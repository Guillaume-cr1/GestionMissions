    private void initTable() {
    try {
        // Les colonnes du tableau
        String[] colonnes = {
            "ID", "Pseudo", "Nom", "Spécialité", "Niveau", "Actif"
        };

        // Création du modèle du tableau
        DefaultTableModel modele = new DefaultTableModel(colonnes, 0);

        // Création du DAO
        AgentDAO dao = new AgentDAO();

        // Récupération de tous les agents
        for (Agent agent : dao.listerAgents()) {

            Object[] ligne = {
                agent.getIdAgent(),
                agent.getPseudo(),
                agent.getNom(),
                agent.getSpecialite(),
                agent.getNiveau(),
                agent.isActif()
            };

            modele.addRow(ligne);
        }

        // Affichage des données dans le tableau
        jTableAgent.setModel(modele);

        // Permet de trier les colonnes
        jTableAgent.setAutoCreateRowSorter(true);

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Erreur lors de la consultation : " + ex.getMessage());
    }
  }
