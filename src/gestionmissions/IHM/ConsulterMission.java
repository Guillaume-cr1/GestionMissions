    private void ouvrirMissionSelectionnee() {
        
        
       
        try {
            System.out.println("méthode selectionnée");
            int ligneVue = jTableMission.getSelectedRow();
            if (ligneVue== -1){
                JOptionPane.showMessageDialog(this, "Sélectionnez une mission .");
                return;
            }
            int ligneModele = jTableMission.convertRowIndexToModel(ligneVue);
            int idMission =(int)jTableMission.getModel().getValueAt(ligneModele,0);
            
            MissionDAO dao =new MissionDAO();
            
            Mission mission = dao.trouverParId(idMission);
            
            ModifierMissionDialog1 unefenetre =new ModifierMissionDialog1(this,mission);
            unefenetre.setVisible(true);
        } catch (SQLException ex) {
            System.getLogger(ConsulterMission.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
       
           
       
       
    }
