    private void initTable(){
        try {
            String[]colonnes = { "ID", "Titre", "Description", "Date de Début","Date de fin", "Statut", "Priorité", "Budget"
            };
            DefaultTableModel modele = new DefaultTableModel(colonnes, 0);
            
            MissionDAO dao =new MissionDAO();
            for (Mission mission : dao.lister2()){
                Object[] ligne ={
                    mission.getId(),mission.getTitre(),mission.getDescription(),
                    mission.getDateDebut(),mission.getDateFin(),
                    mission.getStatut(),mission.getPriorite(),mission.getBudget()
                };
                modele.addRow(ligne);
            }
            jTableMission.setModel(modele);
            jTableMission.setDefaultEditor(Mission.class, null);
            jTableMission.setAutoCreateRowSorter(true);
            
            
        } catch (SQLException ex) {
            System.getLogger(ConsulterMission.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }
