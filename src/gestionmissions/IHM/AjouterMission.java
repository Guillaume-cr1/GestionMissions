    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            Mission missionAjout=new Mission(JTextFieldTitre.getText(),
                    jTextFieldDescription.getText(),
                    LocalDate.parse(dateDebut.getText()),
                    LocalDate.parse(dateFin.getText()),
                    Statut.valueOf(jComboBox1Statut.getSelectedItem().toString()),
                    Priorite.valueOf(jComboBox2Priorite.getSelectedItem().toString()),
                    Double.parseDouble(budget.getText()));
            MissionDAO missionDao = new MissionDAO();
            int reponse=missionDao.ajouter(missionAjout);
            if (reponse ==1){
                JOptionPane jop1;
                jop1 = new JOptionPane();
                jop1.showMessageDialog(null, "Ajout reussi", "information", JOptionPane.INFORMATION_MESSAGE);
            }
            
            MenuMission fenetreMenu = new MenuMission();
            fenetreMenu.setVisible(true);
            this.dispose();
            
        } catch (SQLException ex) {
            System.getLogger(AjouterMission.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
           
                
    }//GEN-LAST:event_jButton2ActionPerformed

