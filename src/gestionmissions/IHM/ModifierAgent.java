    private void jButtonEnregistrerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEnregistrerActionPerformed
        int index = jComboBoxAgent.getSelectedIndex();

    if (index < 0) {
        JOptionPane.showMessageDialog(this,
                "Veuillez sélectionner un agent.");
        return;
    }

    try {
        // Récupérer l'agent sélectionné
        Agent agent = lesAgents.get(index);

        // Récupérer les nouvelles informations
        String pseudo = textPseudo.getText();
        String nom = textNom.getText();
        String specialite = textSpecialite.getText();
        String niveauTexte = textNiveau.getText();
        boolean actif = jCheckBoxActif.isSelected();

        // Vérifier les champs
        if (pseudo.isEmpty() || nom.isEmpty()
                || specialite.isEmpty() || niveauTexte.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Veuillez remplir tous les champs.");
            return;
        }

        // Convertir le niveau en entier
        int niveau = Integer.parseInt(niveauTexte);

        // Mettre à jour l'objet Agent
        agent.setPseudo(pseudo);
        agent.setNom(nom);
        agent.setSpecialite(specialite);
        agent.setNiveau(niveau);
        agent.setActif(actif);

        // Modifier l'agent dans la base de données
        AgentDAO dao = new AgentDAO();
        dao.modifierAgent(agent);

        JOptionPane.showMessageDialog(this,
                "Agent modifié avec succès !");

        // Recharger la liste des agents
        chargerAgents();

        // Replacer la sélection sur l'agent modifié
        jComboBoxAgent.setSelectedIndex(index);

        } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Le niveau doit être un nombre entier.");

        }  catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erreur lors de la modification : " + e.getMessage());
        }
    }//GEN-LAST:event_jButtonEnregistrerActionPerformed

