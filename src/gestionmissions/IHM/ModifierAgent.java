    private void chargerAgents() {
    try {
        AgentDAO dao = new AgentDAO();

        lesAgents = dao.listerAgents();

        jComboBoxAgent.removeAllItems();

        for (Agent agent : lesAgents) {
            jComboBoxAgent.addItem(
                agent.getIdAgent() + " - "
                + agent.getPseudo() + " "
                + agent.getNom()
            );
        }

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Erreur lors du chargement des agents : "
                + ex.getMessage());
    }
}
    
    private void afficherAgentSelectionne() {

    int index = jComboBoxAgent.getSelectedIndex();

    if (index >= 0) {

        Agent agent = lesAgents.get(index);

        textPseudo.setText(agent.getPseudo());
        textNom.setText(agent.getNom());
        textSpecialite.setText(agent.getSpecialite());
        textNiveau.setText(String.valueOf(agent.getNiveau()));
        jCheckBoxActif.setSelected(agent.isActif());
    }
}

