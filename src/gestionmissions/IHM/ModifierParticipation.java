    private void chargerAgents() {
    try {
        AgentDAO dao = new AgentDAO();
        lesAgents = dao.listerAgents();

        comboBoxAgent.removeAllItems();

        for (Agent agent : lesAgents) {
            comboBoxAgent.addItem(agent.getIdAgent() + " - "
                    + agent.getPseudo() + " " + agent.getNom());
        }

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Erreur lors du chargement des agents : " + ex.getMessage());
    }
    }
    
    private void chargerMissions() {
    try {
        MissionDAO dao = new MissionDAO();
        lesMissions = dao.lister2();

        comboBoxMission.removeAllItems();

        for (Mission mission : lesMissions) {
            comboBoxMission.addItem(mission.getTitre());
        }

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Erreur lors du chargement des missions : " + ex.getMessage());
    }
    }
    
    private void chargerParticipations() {
    try {
        ParticipationDAO dao = new ParticipationDAO();
        lesParticipations = dao.lister();

        comboBoxParticipation.removeAllItems();

        for (Object[] participation : lesParticipations) {
            comboBoxParticipation.addItem(
                    participation[1] + " - "
                    + participation[4] + " (" 
                    + participation[5] + ")"
            );
        }

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Erreur lors du chargement des affectations : "
                + ex.getMessage());
    }
}
    private void cbParticipationActionPerformed(java.awt.event.ActionEvent evt) {
    int index = comboBoxParticipation.getSelectedIndex();

    if (index >= 0 && lesParticipations != null) {
        Object[] participation = lesParticipations.get(index);

        ancienIdAgent = (int) participation[0];
        ancienneIdMission = (int) participation[3];

        txtRole.setText((String) participation[5]);
        txtDate.setText(participation[6].toString());

        for (int i = 0; i < lesAgents.size(); i++) {
            if (lesAgents.get(i).getIdAgent() == ancienIdAgent) {
                comboBoxAgent.setSelectedIndex(i);
                break;
            }
        }

        for (int i = 0; i < lesMissions.size(); i++) {
            if (lesMissions.get(i).getId() == ancienneIdMission) {
                comboBoxMission.setSelectedIndex(i);
                break;
            }
        }
    }
}
