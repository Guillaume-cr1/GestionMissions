    private void btnEnregistrerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnregistrerActionPerformed
    int indexAgent = comboBoxAgent.getSelectedIndex();
    int indexMission = comboBoxMission.getSelectedIndex();

    String role = txtRole.getText().trim();
    String dateTexte = txtDate.getText().trim();

    if (indexAgent < 0 || indexMission < 0
            || role.isEmpty() || dateTexte.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Veuillez remplir tous les champs.");
        return;
    }

    try {
        Agent agent = lesAgents.get(indexAgent);
        Mission mission = lesMissions.get(indexMission);

        LocalDate date = LocalDate.parse(dateTexte);

        Participation participation = new Participation(
                agent.getIdAgent(),
                mission.getId(),
                role,
                date
        );

        ParticipationDAO dao = new ParticipationDAO();

        Object[] ancienneParticipation =
                lesParticipations.get(
                        comboBoxParticipation.getSelectedIndex());

        int resultat = dao.modifier(
                participation,
                (int) ancienneParticipation[0],
                (int) ancienneParticipation[3]
        );

        if (resultat > 0) {
            JOptionPane.showMessageDialog(this,
                    "Affectation modifiée avec succès !");

            MenuParticipation menu = new MenuParticipation();
            menu.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Aucune affectation n'a été modifiée.");
        }

    } catch (DateTimeParseException e) {
        JOptionPane.showMessageDialog(this,
                "La date doit être au format AAAA-MM-JJ.");

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Erreur lors de la modification : " + e.getMessage());
    }
    }//GEN-LAST:event_btnEnregistrerActionPerformed

