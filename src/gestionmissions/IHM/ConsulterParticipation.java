    private void chargerParticipations() {
    try {
        ParticipationDAO dao = new ParticipationDAO();
        List<Object[]> participations = dao.lister();

        DefaultTableModel modele = new DefaultTableModel(
                new String[]{
                    "ID Agent",
                    "Pseudo",
                    "Nom",
                    "ID Mission",
                    "Mission",
                    "Rôle",
                    "Date d'affectation"
                }, 0);

        for (Object[] participation : participations) {
            modele.addRow(participation);
        }

        jTable1.setModel(modele);

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this,
                "Erreur lors du chargement des affectations : "
                + ex.getMessage());
    }
}
