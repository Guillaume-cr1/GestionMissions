    private void btnAjouterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAjouterActionPerformed
       // Récupération des informations saisies
    String pseudo = txtPseudo.getText();
    String nom = txtNom.getText();
    String specialite = txtSpecialite.getText();
    String niveauTexte = txtNiveau.getText();
    boolean actif = jCheckBoxActif.isSelected();

    // Vérification des champs
    if (pseudo.isEmpty() || nom.isEmpty()
            || specialite.isEmpty() || niveauTexte.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Veuillez remplir tous les champs.");

    } else {

        try {
            // Conversion du niveau en entier
            int niveau = Integer.parseInt(niveauTexte);

            // Création de l'agent
            Agent nouvelAgent = new Agent(
                    0,pseudo, nom, specialite, niveau, actif
            );

            // Ajout dans la base de données
            AgentDAO agentDAO = new AgentDAO();
            agentDAO.ajouterAgent(nouvelAgent);

            JOptionPane.showMessageDialog(this,
                    "Agent ajouté avec succès !");

            // Vider les champs
            txtPseudo.setText("");
            txtNom.setText("");
            txtSpecialite.setText("");
            txtNiveau.setText("");
            jCheckBoxActif.setSelected(false);

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this,
                    "Le niveau doit être un nombre entier.");

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erreur lors de l'ajout : " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnAjouterActionPerformed

