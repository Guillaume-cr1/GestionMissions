    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            MissionDAO uneMissionDAO=new MissionDAO();
            Mission missionRecup=(Mission) jComboBoxMission.getSelectedItem();
            Mission missionModif=new Mission(
                    jTextFieldTitre.getText(),
                    jTextFieldDescription.getText(),
                    LocalDate.parse(jTextFieldDateDebut.getText()),
                    LocalDate.parse(jTextFieldDateFin.getText()),
                    Statut.valueOf(jComboBoxStatut.getSelectedItem().toString()),
                    Priorite.valueOf(jComboBoxPriorite.getSelectedItem().toString()),
                    Double.parseDouble(jTextFieldBudget.getText()));
            boolean reponse=uneMissionDAO.modifier(missionModif);
            if (reponse) {
                JOptionPane jop1;
                jop1 = new JOptionPane();
                jop1.showMessageDialog(null, "Modification reussie", "Information", JOptionPane.INFORMATION_MESSAGE);
            }
            MenuMission menu=new MenuMission();
            menu.setVisible(true);
            ModifierMission2.this.dispose();
        } catch (SQLException ex) {
            System.getLogger(ModifierMission2.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

