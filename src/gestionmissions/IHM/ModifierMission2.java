    private void initCombox(){
        
        try {
            MissionDAO uneMissionDAO = new MissionDAO();
            jComboBoxMission.removeAllItems();
            //remplissage combobox
            lesMissions = uneMissionDAO.lister2();
            
            for (int i = 0; i < lesMissions.size(); i++ ){
                jComboBoxMission.addItem(lesMissions.get(i));
            }
        } catch (SQLException ex) {
            System.getLogger(ModifierMission2.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
    }
    
    private void initialiserCombox(){
         for (Statut statut : Statut.values()){
            jComboBoxStatut.addItem(statut);
        }
        for (Priorite priorite : Priorite.values()){
            jComboBoxPriorite.addItem(priorite);
        }
    }
